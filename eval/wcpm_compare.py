"""Reading speed versus a human scorer (P3-AI-1): how far is the app's WCPM from a teacher's?

    python eval/wcpm_compare.py          # writes eval/WCPM_REPORT.md

A person fills eval/wcpm_human.csv by listening: `reading_seconds` from a stopwatch (first word to last)
and `words_correct` from the mistakes they hear. The app's numbers come from the saved scores of the last
`run_eval.py` runs (eval/out/predictions.json and confirm_predictions.json), using the engine's own
compute_wcpm() and compute_level(), so this measures what the app shows. Three app versions separate the
error sources:
  - draft:                 the app's labels and the whole recording's length (what the engine does today)
  - confirmed:             labels as the teacher would fix them (the ground truth), whole recording
  - confirmed, read time:  fixed labels, and the time from the first word's start to the last word's end
"""
import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "engine"))

import metrics  # noqa: E402
from app.levels import compute_level, compute_wcpm  # noqa: E402  (the engine's own formulas)

VERSIONS = ("draft", "confirmed", "confirmed, read time")


def load_human(path) -> list:
    """Rows of the form that have both numbers filled in."""
    with open(path, newline="", encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if (r.get("reading_seconds") or "").strip() and (r.get("words_correct") or "").strip()]
    for r in rows:
        r["reading_seconds"], r["words_correct"] = float(r["reading_seconds"]), int(r["words_correct"])
        r["passage_words"] = int(r["passage_words"])
    return rows


def compare(human_rows: list, predictions: dict, recordings: dict) -> list:
    """One result per human row: human and app WCPM and levels. Rows without saved scores are skipped."""
    out = []
    for h in human_rows:
        rid = h["recording_id"]
        pred, rec = predictions.get(rid), recordings.get(rid)
        if pred is None or rec is None:
            continue
        words = pred["words"]
        n = h["passage_words"]
        draft = [w["label"] for w in words]
        fixed = ["skipped" if w["i"] in rec.errors else "matched" for w in words]
        read_time = words[-1]["end"] - words[0]["start"]
        human_wcpm = round(h["words_correct"] * 60 / h["reading_seconds"])
        app = {
            "draft": (compute_wcpm(draft, pred["duration_sec"]), draft.count("matched")),
            "confirmed": (compute_wcpm(fixed, pred["duration_sec"]), fixed.count("matched")),
            "confirmed, read time": (compute_wcpm(fixed, read_time), fixed.count("matched")),
        }
        out.append({
            "recording_id": rid,
            "human_wcpm": human_wcpm,
            "human_level": compute_level(h["words_correct"], n, human_wcpm),
            "human_correct": h["words_correct"],
            "truth_correct": n - len(rec.errors),
            "human_seconds": h["reading_seconds"],
            "recording_seconds": pred["duration_sec"],
            "read_seconds": read_time,
            "app": {v: {"wcpm": wcpm, "level": compute_level(correct, n, wcpm)} for v, (wcpm, correct) in app.items()},
        })
    return out


def summary(results: list) -> dict:
    """Per app version: mean absolute WCPM error, mean signed error (app minus human), level agreement."""
    out = {}
    for v in VERSIONS:
        errors = [r["app"][v]["wcpm"] - r["human_wcpm"] for r in results]
        pct = [abs(e) / r["human_wcpm"] for e, r in zip(errors, results) if r["human_wcpm"]]
        out[v] = {
            "mae": sum(abs(e) for e in errors) / len(errors),
            "bias": sum(errors) / len(errors),
            "mape": sum(pct) / len(pct) if pct else 0.0,
            "same_level": sum(r["app"][v]["level"] == r["human_level"] for r in results),
        }
    return out


def report(results: list) -> str:
    s = summary(results)
    n = len(results)
    lines = ["# Reading speed versus a human scorer", "",
             "Generated by `eval/wcpm_compare.py` from `eval/wcpm_human.csv`. Do not edit by hand.", "",
             f"{n} readings, timed and counted by a person listening with a stopwatch. WCPM = words correct per minute; "
             "app numbers use the engine's `compute_wcpm()` and `compute_level()`.", "",
             "| App version | Mean error (WCPM) | Bias (app − human) | Mean error (%) | Same level as human |",
             "|---|---|---|---|---|"]
    for v in VERSIONS:
        lines.append(f"| {v} | {s[v]['mae']:.1f} | {s[v]['bias']:+.1f} | {s[v]['mape']:.0%} | {s[v]['same_level']}/{n} |")
    lines += ["", "- **draft:** the app's own labels and the whole recording's length (what the engine shows before the teacher confirms).",
              "- **confirmed:** labels as the teacher would fix them, whole recording: what's left is timing.",
              "- **confirmed, read time:** fixed labels, timed from the first word's start to the last word's end (from the aligner).",
              "", "## Per reading", "",
              "| Reading | Human WCPM (level) | Draft | Confirmed | Confirmed, read time | Stopwatch / recording / read time (s) | Words correct: human / truth |",
              "|---|---|---|---|---|---|---|"]
    for r in results:
        a = r["app"]
        lines.append(
            f"| {r['recording_id']} | {r['human_wcpm']} ({r['human_level']}) | {a['draft']['wcpm']} ({a['draft']['level']}) "
            f"| {a['confirmed']['wcpm']} | {a['confirmed, read time']['wcpm']} "
            f"| {r['human_seconds']:.1f} / {r['recording_seconds']:.1f} / {r['read_seconds']:.1f} | {r['human_correct']} / {r['truth_correct']} |"
        )
    lines += ["", "Caveats: one adult reader and one human scorer; adults read far faster than Grade 2 children, so every level "
              "here is near the top. Use it for the size and direction of the error, not for levels.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--human", default=HERE / "wcpm_human.csv")
    ap.add_argument("--predictions", nargs="+", default=[HERE / "out" / "predictions.json", HERE / "out" / "confirm_predictions.json"])
    ap.add_argument("--ground-truth", nargs="+", default=[HERE / "ground_truth.csv", HERE / "confirm_ground_truth.csv"])
    ap.add_argument("--out", default=HERE / "WCPM_REPORT.md")
    args = ap.parse_args(argv)

    human = load_human(args.human)
    if not human:
        print(f"{args.human} has no filled rows yet: add reading_seconds and words_correct.")
        return 1
    predictions, recordings = {}, {}
    for path in args.predictions:
        if not Path(path).exists():
            print(f"missing {path}: run eval/run_eval.py first (see eval/README.md)")
            return 1
        predictions.update(json.loads(Path(path).read_text(encoding="utf-8"))["predictions"])
    for path in args.ground_truth:
        recordings.update(metrics.load_ground_truth(path))
    results = compare(human, predictions, recordings)
    missing = [h["recording_id"] for h in human if h["recording_id"] not in {r["recording_id"] for r in results}]
    if missing:
        print(f"no saved scores for {', '.join(missing)}: re-run eval/run_eval.py")
    if not results:
        return 1
    Path(args.out).write_text(report(results), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
