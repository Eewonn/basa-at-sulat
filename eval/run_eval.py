"""Run the scorer over the test recordings and write eval/REPORT.md (P0-AI-1).

From the repo root, with the venv active:
    python eval/run_eval.py                # score every recording, write eval/REPORT.md
    python eval/run_eval.py --reuse        # rebuild the report from the saved predictions (no model run)
    python eval/run_eval.py --reuse --export-dir data/demo_checks   # also write one score() JSON per recording

Recordings are looked up at eval/recordings/<language>/<recording_id>.wav. Rows in ground_truth.csv
with no matching file are skipped and listed in the report.
"""
import argparse
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

import metrics  # noqa: E402

MAX_LISTED = 12  # per language, per kind of error shown in the report
WORD_KEYS = ("i", "text", "label", "score", "start", "end")  # a word in score()'s result (docs/API.md)


def load_passages(path) -> dict:
    return {p["id"]: p["text"] for p in json.loads(Path(path).read_text(encoding="utf-8"))}


def audio_seconds(path) -> float:
    import soundfile as sf

    return float(sf.info(str(path)).duration)


def evaluate(recordings: dict, passages: dict, recordings_dir, scorer, log=print):
    """Score every recording that has audio. Returns (predictions, skipped).

    predictions: {recording_id: {"language", "passage_id", "duration_sec", "elapsed_sec",
                                 "words": [{"i","text","label","score","start","end"}], "pauses": [...]}}
    skipped: [(recording_id, reason)]
    """
    predictions, skipped = {}, []
    for rec in sorted(recordings.values(), key=lambda r: (r.language, r.id)):
        audio = Path(recordings_dir) / rec.language / f"{rec.id}.wav"
        if not audio.exists():
            skipped.append((rec.id, f"no audio at {audio}"))
            continue
        if rec.passage_id not in passages:
            skipped.append((rec.id, f"passage {rec.passage_id!r} not in passages.json"))
            continue
        started = time.perf_counter()
        result = scorer(str(audio), passages[rec.passage_id])
        elapsed = time.perf_counter() - started
        predictions[rec.id] = {
            "language": rec.language,
            "passage_id": rec.passage_id,
            "duration_sec": audio_seconds(audio),
            "elapsed_sec": elapsed,
            "words": [{k: w[k] for k in WORD_KEYS if k in w} for w in result["words"]],
            "pauses": result.get("pauses", []),
        }
        log(f"scored {rec.id} ({predictions[rec.id]['duration_sec']:.1f}s audio in {elapsed:.1f}s)")
    return predictions, skipped


def _f(x: float) -> str:
    return f"{x:.2f}"


def _by_language(recordings: dict, predictions: dict) -> dict:
    groups = defaultdict(dict)
    for rec_id, pred in predictions.items():
        if rec_id in recordings:  # saved predictions can outlive a row removed from the ground truth
            groups[recordings[rec_id].language][rec_id] = pred
    return dict(sorted(groups.items()))


def _mistakes_listing(recordings: dict, preds: dict, threshold: float):
    """(missed planted mistakes, false alarms) at a threshold, as printable lines."""
    flag = metrics.flag_below(threshold)
    missed, alarms = [], []
    for rec_id, pred in sorted(preds.items()):
        rec = recordings[rec_id]
        for w in pred["words"]:
            gold, flagged = w["i"] in rec.errors, flag(w)
            line = f"{rec_id} word {w['i']} `{w['text']}` score {_f(w['score'])}"
            if gold and not flagged:
                missed.append(f"{line} ({rec.errors[w['i']]})")
            elif flagged and not gold:
                alarms.append(line + (" (clean reading)" if rec.clean else ""))
    return missed, alarms


def machine_info() -> dict:
    """CPU name, hardware threads and this process's peak memory so far (psutil, if installed)."""
    import os
    import platform

    cpu = platform.processor() or platform.machine()
    try:  # Windows keeps the readable name ("AMD Ryzen 5 7520U ...") in the registry
        import winreg

        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, r"HARDWARE\DESCRIPTION\System\CentralProcessor\0") as key:
            cpu = winreg.QueryValueEx(key, "ProcessorNameString")[0].strip()
    except (ImportError, OSError):
        pass
    info = {"cpu": cpu, "threads": os.cpu_count()}
    try:
        import psutil

        mem = psutil.Process().memory_info()
        info["peak_memory_gb"] = round(getattr(mem, "peak_wset", mem.rss) / 2**30, 2)  # peak on Windows, current elsewhere
    except ImportError:
        pass
    return info


def build_report(recordings: dict, predictions: dict, skipped: list, machine: dict | None = None) -> str:
    groups = _by_language(recordings, predictions)
    lines = ["# Aligner test report", "", "Generated by `eval/run_eval.py` from `eval/ground_truth.csv`. Do not edit by hand.", ""]

    # Set size
    lines += ["## Test set", "", "| Language | Recordings scored | Clean | Planted swap/skip (scored) | Inserts (not scored) |", "|---|---|---|---|---|"]
    for lang, preds in groups.items():
        recs = [recordings[r] for r in preds]
        lines.append(
            f"| {lang} | {len(recs)} | {sum(r.clean for r in recs)} | {sum(len(r.errors) for r in recs)} "
            f"| {sum(len(r.inserts) for r in recs)} |"
        )
    if skipped:
        lines += ["", f"{len(skipped)} recording(s) in the ground truth were not scored:"]
        lines += [f"- `{rec_id}`: {reason}" for rec_id, reason in skipped]
    if not groups:
        return "\n".join(lines + ["", "**No recordings were scored, so there is no verdict.**", ""])

    # Headline numbers
    lines += [
        "",
        "## Mistake detection",
        "",
        "A word counts as flagged when `ai.score` labels it `misread` or `skipped`. Precision = real mistakes among flagged words; "
        "recall = planted mistakes we caught.",
        "",
        "| Language | Setting | Precision | Recall | F1 |",
        "|---|---|---|---|---|",
    ]
    gate = {}
    details = {}
    for lang, preds in groups.items():
        labels = metrics.prf(metrics.confusion(recordings, preds))
        lines.append(f"| {lang} | labels from `score()` | {_f(labels['precision'])} | {_f(labels['recall'])} | {_f(labels['f1'])} |")
        best = metrics.best_threshold(recordings, preds)
        cv = metrics.held_out(recordings, preds)
        if best:
            t, b = best
            lines.append(
                f"| {lang} | best score cutoff (≤ {_f(t)}), tuned on this set | {_f(b['precision'])} | {_f(b['recall'])} | {_f(b['f1'])} |"
            )
            details[lang] = t
        if cv:
            lines.append(f"| {lang} | cutoff chosen on half, tested on the other half | {_f(cv['precision'])} | {_f(cv['recall'])} | {_f(cv['f1'])} |")
        gate[lang] = (cv or (best[1] if best else None) or {}).get("f1")

    # Verdict
    lines += ["", "## Go / no-go", "", f"Gate: F1 of {metrics.GATE_F1} or better. We use the held-out F1 (cutoff picked on one half, tested on the other) "
              "because the tuned F1 is measured on the data it was tuned on and flatters us. "
              "With few recordings, treat close calls as close.", ""]
    for lang, f1 in gate.items():
        lines.append(f"- **{lang}:** {metrics.verdict(f1)}" + (f" (F1 {_f(f1)})" if f1 is not None else ""))
    verdicts = {metrics.verdict(f1) for f1 in gate.values()}
    overall = "GO" if verdicts == {"GO"} else "NO-GO" if "NO-GO" in verdicts else "NOT ENOUGH DATA"
    lines += ["", f"**Overall: {overall}**"]

    # Recall by type
    lines += ["", "## Recall by mistake type", "", "At the `score()` labels. Caught / planted.", "", "| Language | swap | skip |", "|---|---|---|"]
    for lang, preds in groups.items():
        r = metrics.recall_by_type(recordings, preds)
        lines.append(f"| {lang} | {r['swap'][0]}/{r['swap'][1]} | {r['skip'][0]}/{r['skip'][1]} |")

    # Speed
    lines += ["", "## Speed", "", "Processing time per minute of audio, on the machine that ran this.", "", "| Language | Audio (s) | Processing (s) | Seconds per audio minute |", "|---|---|---|---|"]
    for lang, preds in groups.items():
        audio = sum(p["duration_sec"] for p in preds.values())
        took = sum(p["elapsed_sec"] for p in preds.values())
        lines.append(f"| {lang} | {audio:.1f} | {took:.1f} | {took / (audio / 60):.1f} |" if audio else f"| {lang} | 0 | {took:.1f} | n/a |")

    if machine:
        lines += ["", f"Machine: {machine.get('cpu', 'unknown CPU')}, {machine.get('threads', '?')} threads. "
                  f"Peak memory of the scoring process: {machine['peak_memory_gb']:.1f} GB."
                  if machine.get("peak_memory_gb") else f"Machine: {machine.get('cpu', 'unknown CPU')}."]
    lines += ["", "Reading speed (WCPM) versus a human scorer: see `eval/WCPM_REPORT.md` (`eval/wcpm_compare.py`)."]

    # What went wrong
    lines += ["", "## Misses and false alarms at the tuned cutoff", "", f"Up to {MAX_LISTED} of each per language. Read these before trusting any number above."]
    for lang, preds in groups.items():
        if lang not in details:
            continue
        missed, alarms = _mistakes_listing(recordings, preds, details[lang])
        lines += ["", f"### {lang} (cutoff ≤ {_f(details[lang])})", "", f"Missed planted mistakes ({len(missed)}):"]
        lines += [f"- {m}" for m in missed[:MAX_LISTED]] or ["- none"]
        lines += ["", f"False alarms ({len(alarms)}):"]
        lines += [f"- {a}" for a in alarms[:MAX_LISTED]] or ["- none"]

    lines += [
        "",
        "## Caveats",
        "",
        "- All readers are adults. Accuracy on children's speech is unknown.",
        "- Inserted words are not part of precision/recall/F1: they have no passage word to flag.",
        "- Thresholds are tuned on this set only. Demo recordings must never be used for tuning.",
        "",
    ]
    return "\n".join(lines)


def export_checks(predictions: dict, out_dir) -> list:
    """Write one JSON per scored recording: recording_id, passage_id, duration_sec and score()'s words and pauses.

    For Backend 2's demo seed data. No audio and no reader initials, only what score() returned. These are
    test recordings by adults, so they're fine to display but not evidence of accuracy, and adult reading
    speed puts every check at the top level unless duration_sec is set synthetically.
    Returns the paths written. Raises ValueError for predictions saved before timings were kept.
    """
    out = Path(out_dir)
    stale = [rid for rid, p in predictions.items()
             if "pauses" not in p or "passage_id" not in p or any("start" not in w for w in p["words"])]
    if stale:
        raise ValueError(f"saved predictions lack word timings or pauses ({', '.join(sorted(stale)[:3])}...): "
                         "they're from an older run_eval.py, so re-run without --reuse")
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for rid, p in sorted(predictions.items()):
        check = {
            "recording_id": rid,
            "passage_id": p["passage_id"],
            "duration_sec": round(p["duration_sec"], 2),
            "words": [{k: w[k] for k in WORD_KEYS} for w in p["words"]],
            "pauses": p["pauses"],
        }
        path = out / f"{rid}.json"
        path.write_text(json.dumps(check, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        written.append(path)
    return written


def main(argv=None, scorer=None) -> int:
    """CLI entry point. `scorer` replaces ai.score (tests pass a stub so they never load the model)."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ground-truth", default=HERE / "ground_truth.csv")
    ap.add_argument("--recordings", default=HERE / "recordings")
    ap.add_argument("--passages", default=ROOT / "data" / "passages" / "passages.json")
    ap.add_argument("--predictions", default=HERE / "out" / "predictions.json", help="where scores are saved / reloaded from")
    ap.add_argument("--out", default=HERE / "REPORT.md")
    ap.add_argument("--reuse", action="store_true", help="rebuild the report from saved predictions without running the model")
    ap.add_argument("--export-dir", help="also write one score() JSON per recording here (demo seed data)")
    args = ap.parse_args(argv)

    recordings = metrics.load_ground_truth(args.ground_truth)
    if not recordings:
        print(f"{args.ground_truth} has no rows yet. Record the test set first (eval/README.md).")
        return 1

    predictions_path = Path(args.predictions)
    if args.reuse:
        saved = json.loads(predictions_path.read_text(encoding="utf-8"))
        predictions, skipped = saved["predictions"], [tuple(s) for s in saved["skipped"]]
        machine = saved.get("machine")
    else:
        if scorer is None:
            sys.path.insert(0, str(ROOT))
            import ai

            print("loading the aligner model...")
            ai.warm_up()  # load before timing, or the first recording's time includes the ~10 s load
            scorer = ai.score
        predictions, skipped = evaluate(recordings, load_passages(args.passages), args.recordings, scorer)
        predictions_path.parent.mkdir(parents=True, exist_ok=True)
        machine = machine_info()
        predictions_path.write_text(json.dumps({"predictions": predictions, "skipped": skipped, "machine": machine},
                                               indent=1), encoding="utf-8")

    report = build_report(recordings, predictions, skipped, machine)
    Path(args.out).write_text(report, encoding="utf-8")
    print(f"wrote {args.out}")
    if args.export_dir:
        try:
            written = export_checks(predictions, args.export_dir)
        except ValueError as err:
            print(f"export failed: {err}")
            return 1
        print(f"exported {len(written)} check(s) to {args.export_dir}")
    return 0 if predictions else 1


if __name__ == "__main__":
    sys.exit(main())
